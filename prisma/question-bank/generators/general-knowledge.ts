import { BankQuestion, Diff, ALL_EXAMS, pick, q } from '../types';

type Out = BankQuestion[];
type Fact = [string, string, string[], string, Diff];

function facts(subject: string, chapter: string, topic: string, list: Fact[]): Out {
  return list.map(([stem, ans, ds, ex, d], i) =>
    q({
      key: `${subject}:${topic}:f${i}:${stem.slice(0, 40)}`,
      subject,
      chapter,
      topic,
      difficulty: d,
      stem,
      answer: ans,
      distractors: ds,
      explanation: ex,
      exams: ALL_EXAMS,
    }),
  );
}

function mapping(
  subject: string,
  chapter: string,
  topic: string,
  rows: Array<[string, string]>,
  stem: (x: string) => string,
  ex: (x: string, y: string) => string,
  d: Diff = 'EASY',
  reverse?: (y: string) => string,
): Out {
  const answers = [...new Set(rows.map((r) => r[1]))];
  const keys = rows.map((r) => r[0]);
  const out: Out = [];
  for (const [x, y] of rows) {
    out.push(
      q({
        key: `${subject}:${topic}:${stem(x)}`,
        subject,
        chapter,
        topic,
        difficulty: d,
        stem: stem(x),
        answer: y,
        distractors: pick(answers, 3, `${topic}-${x}`, (a) => a === y),
        explanation: ex(x, y),
        exams: ALL_EXAMS,
      }),
    );
    // Reverse direction only when the mapping is one-to-one.
    if (reverse && rows.filter((r) => r[1] === y).length === 1)
      out.push(
        q({
          key: `${subject}:${topic}:rev:${reverse(y)}`,
          subject,
          chapter,
          topic,
          difficulty: d,
          stem: reverse(y),
          answer: x,
          distractors: pick(keys, 3, `${topic}-rev-${y}`, (k) => k === x),
          explanation: ex(x, y),
          exams: ALL_EXAMS,
        }),
      );
  }
  return out;
}

